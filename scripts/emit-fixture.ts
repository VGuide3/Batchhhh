#!/usr/bin/env node
/**
 * Emits the canonical reference-batch fixture as JSON (§16). The Foundry
 * cross-language test consumes this file to prove the TypeScript encoder and the
 * Solidity decoder agree byte-for-byte.
 *
 *   node --experimental-strip-types scripts/emit-fixture.ts
 *   # or, after build: node dist/scripts/emit-fixture.js
 */

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { keccak256, toHex } from "viem";
import { USDC, USDT } from "../src/registry.js";
import { buildReferenceFixture } from "../test/fixtures/reference.js";
import { decodeBatch } from "../src/codec/batch.js";

const here = dirname(fileURLToPath(import.meta.url));
const outPath = resolve(here, "../contracts/test/fixtures/reference_batch.json");

const batchId = keccak256(toHex("reference-batch")).slice(0, 2 + 48) as `0x${string}`;
const fixture = buildReferenceFixture({ usdc: USDC, usdt: USDT, batchId });
const decoded = decodeBatch(fixture.packed);

const payload = {
  note: "Generated by scripts/emit-fixture.ts — do not edit by hand.",
  usdc: USDC,
  usdt: USDT,
  batchId,
  salt: fixture.salt,
  sourceCount: decoded.header.sourceCount,
  recordCount: decoded.header.recordCount,
  byteLength: (fixture.packed.length - 2) / 2,
  authorities: fixture.authorities,
  packed: fixture.packed,
};

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, `${JSON.stringify(payload, null, 2)}\n`);
console.log(`wrote ${outPath} (${payload.byteLength} bytes, ${payload.recordCount} records)`);
